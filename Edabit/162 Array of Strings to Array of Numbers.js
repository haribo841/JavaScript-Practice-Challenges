//Create a function that takes as a parameter an array of "stringified" numbers and returns an array of numbers.
function toNumberArray(arr) {
    return arr.map(Number);
}
import { assertEquals } from '../testHelper.js';
assertEquals(toNumberArray(["1", "2"]), [1, 2])
assertEquals(toNumberArray(["3", "4"]), [3, 4])
assertEquals(toNumberArray(["5", "6"]), [5, 6])
assertEquals(toNumberArray(["7", "8"]), [7, 8])
assertEquals(toNumberArray(["9", "10"]), [9, 10])
assertEquals(toNumberArray(["91", "44"]), [91, 44])
assertEquals(toNumberArray(["19", "14"]), [19, 14])
assertEquals(toNumberArray(["29", "34"]), [29, 34])
assertEquals(toNumberArray(["0", "4"]), [0, 4])
assertEquals(toNumberArray(["21", "23"]), [21, 23])
assertEquals(toNumberArray(["12", "25"]), [12, 25])
assertEquals(toNumberArray(["99", "20"]), [99, 20])
assertEquals(toNumberArray(["9", "4", "5", "6", "7", "8", "9"]), [9, 4, 5, 6, 7, 8, 9])
assertEquals(toNumberArray(["11", "14", "13", "12", "3", "6"]), [11, 14, 13, 12, 3, 6])
assertEquals(toNumberArray(["7", "14", "16", "18", "19", "20"]), [7, 14, 16, 18, 19, 20])
assertEquals(toNumberArray(["9.4", "4.2"]), [9.4, 4.2])
assertEquals(toNumberArray(["1.4", "4.4", "5.7", "4.3", "9.8", "5.3", "8.7", "8.6", "9.8"]), [1.4, 4.4, 5.7, 4.3, 9.8, 5.3, 8.7, 8.6, 9.8])
assertEquals(toNumberArray(["9.5", "8.8"]), [9.5, 8.8])
assertEquals(toNumberArray(["3.4", "8.6"]), [3.4, 8.6])
assertEquals(toNumberArray(["5.9", "1.5", "7.8", "4.9", "8.5", "8.4"]), [5.9, 1.5, 7.8, 4.9, 8.5, 8.4])
assertEquals(toNumberArray(["8.7"]), [8.7])
assertEquals(toNumberArray(["7.0", "4.7", "8.4"]), [7, 4.7, 8.4])
assertEquals(toNumberArray(["7.2", "9.7", "4.0", "9.7", "6.5"]), [7.2, 9.7, 4, 9.7, 6.5])
assertEquals(toNumberArray(["9.3", "3.9", "7.9", "4.7"]), [9.3, 3.9, 7.9, 4.7])
assertEquals(toNumberArray(["4.1", "2.9", "1.7"]), [4.1, 2.9, 1.7])
assertEquals(toNumberArray(["9.0", "3.8", "8.8"]), [9, 3.8, 8.8])
assertEquals(toNumberArray(["6.0", "6.9", "3.7", "6.9", "8.3", "7.8", "1.5", "2.6"]), [6, 6.9, 3.7, 6.9, 8.3, 7.8, 1.5, 2.6])
assertEquals(toNumberArray(["9.2", "5.8", "1.3", "3.4", "3.0", "8.5", "3.4", "6.8", "9.9"]), [9.2, 5.8, 1.3, 3.4, 3, 8.5, 3.4, 6.8, 9.9])
assertEquals(toNumberArray(["8.3", "9.7", "8.0"]), [8.3, 9.7, 8])
assertEquals(toNumberArray(["2.1", "1.7", "7.0", "4.7", "9.3", "6.8", "9.1", "9.1"]), [2.1, 1.7, 7, 4.7, 9.3, 6.8, 9.1, 9.1])
assertEquals(toNumberArray(["9.8", "4.6", "7.3", "7.4", "1.9", "6.3", "8.7"]), [9.8, 4.6, 7.3, 7.4, 1.9, 6.3, 8.7])
assertEquals(toNumberArray(["2.4"]), [2.4])